def list_cpu_profiles() -> List[dict]:
    """Return profiles as JSON-ready dicts for the UI."""
    return [
        {"id": p.id, "label": p.label, "speed_index": p.speed_index}
        for p in sorted(CPU_PROFILES.values(), key=lambda x: x.label.lower())
    ]


def get_cpu_profile(cpu_id: Optional[str]) -> CPUProfile:
    if cpu_id:
        key = str(cpu_id).strip().lower()
        if key in CPU_PROFILES:
            return CPU_PROFILES[key]
    return CPU_PROFILES["i5-9500t"]
