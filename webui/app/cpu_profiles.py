"""
CPU profiles for rough encode speed estimation.

We use a simple relative "speed_index" (higher = faster), anchored to:
  i5-9500T = 1.00

This is NOT scientific; it's meant to be "good enough" for ETA guesses.
Real encode speed varies heavily by:
- codec (H.264 vs HEVC vs AV1), encoder (x264/x265/svt-av1), and settings
- resolution, filters (deinterlace/denoise), HDR tone mapping, etc.
- thermals / power limits (especially "T" parts and small OptiPlex cases)
"""

